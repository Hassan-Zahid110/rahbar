"""Prometheus metrics at /metrics (section 4.8).

Exposes request count & latency, retrieval latency, generation latency,
semantic cache lookups & hit ratio, abstention count, fallback count, and
tokens in/out per request.
"""

from __future__ import annotations

from fastapi import APIRouter, Response
from prometheus_client import CONTENT_TYPE_LATEST, Counter, Gauge, Histogram, generate_latest

router = APIRouter()

REQUESTS = Counter("rahbar_requests_total", "HTTP requests", ["path", "status"])
LATENCY = Histogram(
    "rahbar_request_seconds",
    "HTTP request latency",
    ["path"],
    buckets=(0.05, 0.1, 0.25, 0.5, 1, 2, 5, 10, 30, 60, 120),
)

RETRIEVAL_LATENCY = Histogram(
    "rahbar_retrieval_seconds",
    "Vector store retrieval latency in seconds",
    buckets=(0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1, 2, 5),
)
GENERATION_LATENCY = Histogram(
    "rahbar_generation_seconds",
    "LLM generation latency in seconds",
    buckets=(0.05, 0.1, 0.25, 0.5, 1, 2, 5, 10, 20, 45, 90),
)

CACHE_LOOKUPS = Counter(
    "rahbar_cache_lookups_total",
    "Semantic cache lookup outcomes",
    ["result"],  # hit | miss | skipped
)
CACHE_HIT_RATIO = Gauge(
    "rahbar_cache_hit_ratio",
    "Current semantic cache hit ratio (hits / (hits + misses))",
)

ABSTENTIONS = Counter(
    "rahbar_abstentions_total",
    "Questions declined honestly",
    ["reason"],  # below_relevance_floor | model_declined | fallback
)
FALLBACKS = Counter(
    "rahbar_fallbacks_total",
    "Safe fallback responses served after validation or provider failure",
)

TOKENS_IN = Counter(
    "rahbar_tokens_in_total",
    "Total input tokens sent to the LLM provider",
)
TOKENS_OUT = Counter(
    "rahbar_tokens_out_total",
    "Total output tokens generated by the LLM provider",
)

_hits = 0
_misses = 0


def record_cache_outcome(hit: bool) -> None:
    global _hits, _misses
    if hit:
        _hits += 1
        CACHE_LOOKUPS.labels(result="hit").inc()
    else:
        _misses += 1
        CACHE_LOOKUPS.labels(result="miss").inc()
    total = _hits + _misses
    if total > 0:
        CACHE_HIT_RATIO.set(_hits / total)


@router.get("/metrics")
def metrics() -> Response:
    return Response(generate_latest(), media_type=CONTENT_TYPE_LATEST)
